import { createRequire } from 'node:module'
import { mkdir, writeFile } from 'node:fs/promises'
const require=createRequire(process.env.UJELADEA_UI_PACKAGE_JSON||new URL('../package.json',import.meta.url))
const { chromium }=require('playwright')
const expect=require('playwright/test').expect.configure({timeout:25000})
const origin=process.env.UJELADEA_DEMO_URL||'http://127.0.0.1:5178'
if(!/^http:\/\/127\.0\.0\.1:/.test(origin))throw Error('Solo se admite la demo local')
await mkdir('.local-db/demo',{recursive:true})
const state=await(await fetch(origin+'/demo/estado')).json()
const browser=await chromium.launch({channel:process.env.UJELADEA_UI_BROWSER||'msedge',headless:true})
const context=await browser.newContext({viewport:{width:1440,height:1000}})
const errores=[],solicitudes=[],checks=[]
const page=await context.newPage()
page.on('pageerror',e=>errores.push(e.message))
page.on('request',r=>{if(['fetch','xhr','websocket'].includes(r.resourceType()))solicitudes.push(r.url())})
const ok=s=>{checks.push(s);console.log('OK:',s)}
try {
  await page.goto(origin+state.enlaces.panel)
  await expect(page.getByRole('heading',{name:'Segunda etapa · Efesios'})).toBeVisible()
  await expect(page.getByRole('button',{name:'Ingresar a Efesios'})).toBeVisible()
  await page.screenshot({path:'.local-db/demo/panel.png',fullPage:true})
  ok('el panel inicia sesión y verifica el banco de demostración')
  await page.getByRole('button',{name:'Ingresar a Efesios'}).click()
  await expect(page.getByRole('heading',{name:'Sesiones de Efesios'})).toBeVisible()
  await page.getByRole('link',{name:'Preguntas',exact:true}).click()
  await expect(page.getByText('45 activas · 45 en total',{exact:true})).toBeVisible()
  await expect(page.getByText('El banco y las rúbricas están fijos durante la evaluación.',{exact:true})).toBeVisible()
  await page.getByRole('link',{name:'Ranking',exact:true}).click()
  await expect(page.getByRole('button',{name:'Informe para el jurado'})).toBeEnabled()
  ok('el panel muestra sesiones, banco y ranking')
  await page.goto(origin+'/admin/sociedades')
  await expect(page.getByRole('heading',{name:'Gestión de Sociedades'})).toBeVisible()
  await expect(page.getByText('Sociedad histórica de muestra',{exact:true})).toBeVisible()
  ok('la gestión de sociedades carga sin errores heredados')
  const aislado=await browser.newContext()
  const fallo=await aislado.newPage()
  await fallo.goto(origin+state.enlaces.panel)
  await expect(fallo.getByRole('button',{name:'Ingresar a Efesios'})).toBeVisible()
  await fallo.route('**/src/pages/admin/GestionSociedades.jsx*',r=>r.abort())
  await fallo.goto(origin+'/admin/sociedades')
  await expect(fallo.getByRole('heading',{name:'No se pudo cargar esta pantalla'})).toBeVisible()
  await fallo.unroute('**/src/pages/admin/GestionSociedades.jsx*')
  await fallo.getByRole('button',{name:'Volver a cargar'}).click()
  await expect(fallo.getByRole('heading',{name:'Gestión de Sociedades'})).toBeVisible()
  await aislado.close()
  ok('un fallo al descargar una pantalla muestra recuperación y permite recargar')
  await page.goto(origin+'/admin/sesion/'+state.espera+'/espera')
  await expect(page.getByRole('button',{name:/Iniciar/i})).toBeVisible()
  ok('la sala de control carga su sociedad y participantes')
  const moderador=await context.newPage()
  async function aprobarPantalla(){
    await expect(page.getByRole('heading',{name:'El moderador autoriza tu acceso'})).toBeVisible()
    await page.getByRole('button',{name:'Solicitar autorización',exact:true}).click()
    await moderador.goto(origin+'/admin/sesion/'+state.curso+'/espera',{waitUntil:'networkidle'})
    const fila=moderador.locator('.participante-control').filter({has:moderador.getByRole('heading',{name:'Joven en pregunta 20',exact:true})})
    await fila.getByRole('button',{name:'Autorizar acceso',exact:true}).click()
    await moderador.getByLabel('Motivo de la autorización').fill('Identidad comprobada en el recorrido de demostración')
    await moderador.getByRole('dialog').getByRole('button',{name:'Aceptar',exact:true}).click()
    await expect(moderador.getByRole('dialog')).toHaveCount(0)
    await page.evaluate(()=>globalThis.window.dispatchEvent(new Event('online')))
  }
  await page.goto(origin+state.enlaces.examen)
  await aprobarPantalla()
  await expect(page.getByText('Pregunta 20 de 45',{exact:true})).toBeVisible()
  await page.screenshot({path:'.local-db/demo/joven.png',fullPage:true})
  await page.reload()
  await aprobarPantalla()
  await expect(page.getByText('Pregunta 20 de 45',{exact:true})).toBeVisible()
  await page.setViewportSize({width:390,height:844})
  await page.screenshot({path:'.local-db/demo/joven-movil.png',fullPage:true})
  if(!await page.evaluate(()=>globalThis.document.documentElement.scrollWidth<=globalThis.innerWidth))throw Error('Desbordamiento móvil')
  await moderador.close()
  ok('el examen recupera pregunta 20 tras autorización y se adapta a móvil')
  await page.goto(origin+state.enlaces.finalizado)
  await expect(page.getByRole('heading',{name:'Tu examen ha finalizado'})).toBeVisible()
  await page.goto(origin+state.enlaces.registro)
  await expect(page.getByRole('heading',{name:/^(Selecciona tu nombre|El examen comenzará pronto|Tu examen ha finalizado)$/})).toBeVisible()
  ok('los recorridos de registro y finalización están disponibles')
  const externas=solicitudes.filter(u=>!u.startsWith(origin+'/')&&!u.startsWith(origin.replace('http:','ws:')+'/'))
  if(externas.length)throw Error('Petición externa: '+externas.join(','))
  if(errores.length)throw Error(errores.join('\n'))
  ok('sin errores de React ni conexiones de datos externas')
  await writeFile('.local-db/demo/verificacion.json',JSON.stringify({checks,errores,externas},null,2))
} catch(error) {
  console.error(error.stack)
  console.error((await page.locator('body').innerText()).slice(0,5000))
  await page.screenshot({path:'.local-db/demo/fallo.png',fullPage:true})
  process.exitCode=1
} finally { await browser.close() }
